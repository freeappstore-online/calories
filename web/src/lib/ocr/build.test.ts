// @vitest-environment node
import { readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { ASSETS } from "./assets";
import { ENGINE_ORDER } from "./chain";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..", "..");
const OCR = join(root, "web", "public", "ocr");

interface Builder {
  buildEngines(): Promise<Map<string, Uint8Array>>;
  buildTransformers(): Promise<Map<string, Uint8Array>>;
}
const loadBuilder = async () => (await import(/* @vite-ignore */ join(root, "scripts", "build-ocr-engines.mjs"))) as Builder;

/** Files that are generated at build time rather than committed */
const GENERATED = new Set(["transformers.min.mjs"]);

describe("self-hosted engine files", () => {
  it("engine code in public/ocr matches its source (run `node scripts/build-ocr-engines.mjs` after changing it)", async () => {
    const built = await (await loadBuilder()).buildEngines();
    expect([...built.keys()].sort()).toEqual(["engine-florence.mjs", "engine-paddle.mjs", "engine-tesseract.mjs"]);
    for (const [name, bytes] of built) {
      expect(Buffer.compare(readFileSync(join(OCR, name)), Buffer.from(bytes)) === 0, name).toBe(true);
    }
  }, 60_000);

  it("every committed file an engine downloads exists with exactly the size the app expects, and stays under the 25 MB per-file limit", () => {
    for (const id of ENGINE_ORDER) {
      for (const a of ASSETS[id]) {
        if (!a.url.includes("/ocr/") || GENERATED.has(a.name)) continue;
        const size = statSync(join(OCR, a.name)).size;
        expect(size, a.name).toBe(a.bytes);
        expect(size, a.name).toBeLessThan(25 * 1024 * 1024);
      }
    }
  });

  it("the transformers.js bundle (generated by every `pnpm build`) is about the size the app expects and under the 25 MB limit", async () => {
    const built = (await (await loadBuilder()).buildTransformers()).get("transformers.min.mjs")!;
    const expected = ASSETS.florence.find((a) => a.name === "transformers.min.mjs")!;
    // Not byte for byte: the bundle differs by a few bytes between machines (it only feeds the download's progress bar)
    expect(Math.abs(built.byteLength - expected.bytes) / expected.bytes).toBeLessThan(0.01);
    expect(built.byteLength).toBeLessThan(25 * 1024 * 1024);
  }, 60_000);

  it("only the plain core is listed when WebAssembly SIMD is missing, never both", () => {
    const cores = ASSETS.tesseract.filter((a) => a.name.startsWith("tesseract-core"));
    expect(cores).toHaveLength(1);
  });
});
